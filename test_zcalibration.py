        with open(locs_yaml, "w", encoding="utf-8") as h:
            yaml.safe_dump_all([{"Frames": 5}, {"Generated by": "Picasso Localize", "Z Calibration": cal,
                                               "Z Calibration Path": f2026}], h)
        r26 = zcal.read_calibration_file(f2026)
        assert r26.layout == zcal.LAYOUT_CALIBRATION_FILE and r26.origin == zcal.ORIGIN_CHOSEN
        assert r26.magnification == 0.79 and r26.file_name == "stack_3d_calib.yaml"
        r23 = zcal.read_calibration_file(f2023)
        assert r23.magnification is None and r23.n_frames is None and r23.has_curves
        rts = zcal.read_calibration_file(thunder)
        assert rts.layout == zcal.LAYOUT_THUNDERSTORM and not rts.has_curves
        cols = zcal.export_columns(zcal.ZCalibrationState(chosen_record=rts))
        assert cols["z_calibration_source"] == "chosen record (ThunderSTORM)" and cols["z_magnification"] is None
        rl = zcal.read_calibration_file(locs_yaml)
