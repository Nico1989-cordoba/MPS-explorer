def test_layouts_and_derived_ranges() -> None:
    rng = np.random.default_rng(1)
    checked = 0
    for m in M_VALUES:
        for _ in range(4):
            n = int(rng.integers(41, 122))
            step = float(rng.choice([20.0, 25.0, 30.0, 50.0]))
            z0 = float(rng.uniform(-150, 150))
            cal = calibration_dict(n, step, m, z0)
            info_old = [{"Frames": 10}, {"Generated by": "Picasso Localize", "Z Calibration": cal,
                                         "Z Calibration Path": "C:/somewhere/stack_3d_calib.yaml"}]
            fit3d = dict(cal, **{"Generated by": "Picasso v0.11 Fit 3D", "Calibration path": "/x/y/new_3d_calib.yaml",
                                 "Filter range": 2, "Frames per step": 1, "Frame order": "fov", "Path": "N/A"})
            info_new = [{"Frames": 10}, {"Generated by": "Picasso v0.11 Localize"}, fit3d]
            for info, layout, name in ((info_old, zcal.LAYOUT_Z_CALIBRATION, "stack_3d_calib.yaml"),
                                       (info_new, zcal.LAYOUT_FIT_3D, "new_3d_calib.yaml")):
                rec = zcal.record_from_info(info)
                assert rec is not None and rec.layout == layout and rec.origin == zcal.ORIGIN_FILE
                assert rec.file_name == name                       # the name, never the folder
                assert rec.magnification == m and rec.n_steps == n
                half = (n - 1) * step / 2.0
                lo, hi = rec.nominal_bounds_nm(m)
                assert abs(lo + half * m) < 1.0 and abs(hi - half * m) < 1.0
                true_lo, true_hi = (-half - z0) * m, (half - z0) * m
                assert abs(lo - true_lo) <= abs(z0) * m + 1e-6 and abs(hi - true_hi) <= abs(z0) * m + 1e-6
                st = zcal.ZCalibrationState(file_record=rec)
                cols = zcal.export_columns(st)
                assert abs(cols["z_calibrated_range_nm"] - 2 * half * m) < 1.0
                assert cols["z_calibrated_range_origin"] == "nominal"
                assert abs(rec.crossing_nm()) < 1.0             # the curves cross at 0 by construction
                assert zcal.validate_record(rec) == [], zcal.validate_record(rec)
                checked += 1
            assert zcal.record_from_info(info_new).filter_range == 2
    assert checked == 2 * 4 * len(M_VALUES)


def test_fit_bounds_and_frame_bounds() -> None:
    for m in M_VALUES:
        rec = zcal.record_from_mapping(calibration_dict(81, 25.0, m), layout=zcal.LAYOUT_Z_CALIBRATION,
                                       origin=zcal.ORIGIN_FILE)
        cov = __import__("tools.mps_quality", fromlist=["axial_coverage"]).axial_coverage(
            np.linspace(-300, 300, 50), rec, 190.0)
        assert abs(cov.fit_bound_nm - 1000.0 * m) < 1e-9
    # frames per step: 123 frames, 3 per step -> 41 steps
    rec = zcal.record_from_mapping(calibration_dict(41, 25.0, 0.79, **{"Number of frames": 123, "Frames per step": 3}),
                                   layout=zcal.LAYOUT_FIT_3D, origin=zcal.ORIGIN_FILE)
