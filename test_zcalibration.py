def test_each_validation_rule_fires() -> None:
    good = calibration_dict(81, 25.0, 0.79)

    def problems(**change: Any) -> List[str]:
        d = dict(good, **change)
        return zcal.validate_record(zcal.record_from_mapping(d, layout=zcal.LAYOUT_CALIBRATION_FILE,
                                                             origin=zcal.ORIGIN_CHOSEN))
    assert problems() == []
    assert any("not positive" in p for p in problems(**{"Step size in nm": -25.0}))
    assert any("fewer than" in p for p in problems(**{"Number of frames": 4}))
    assert any("outside" in p for p in problems(**{"Magnification factor": 1.5}))
    assert any("outside" in p for p in problems(**{"Magnification factor": 0.3}))
    assert any("not readable" in p for p in problems(**{"X Coefficients": [1, 2, "a"]}))
    # curves shifted: they cross 100 nm off zero (more than half a step)
    shifted = calibration_dict(81, 25.0, 0.79)
    z = np.linspace(-1000, 1000, 81)
    sx, sy = widths(z - 100.0)
    shifted["X Coefficients"] = [float(c) for c in np.polyfit(z, sx, 6)]
    shifted["Y Coefficients"] = [float(c) for c in np.polyfit(z, sy, 6)]
    p = zcal.validate_record(zcal.record_from_mapping(shifted, layout=zcal.LAYOUT_FIT_3D, origin=zcal.ORIGIN_FILE))
    assert any("cross at +100" in q for q in p), p
    # curves that never cross
    flat = dict(good, **{"Y Coefficients": [0, 0, 0, 0, 0, 0, 5.0], "X Coefficients": [0, 0, 0, 0, 0, 0, 1.0]})
    assert any("do not cross" in q for q in zcal.validate_record(
        zcal.record_from_mapping(flat, layout=zcal.LAYOUT_FIT_3D, origin=zcal.ORIGIN_FILE)))
    # wx - wy not monotone over the range: a turn inside +/-1000
    turn = dict(good)
    turn["X Coefficients"] = [0, 0, 0, 0, 1e-6, 0, 1.0]       # wx = 1 + 1e-6 z^2
    turn["Y Coefficients"] = [0, 0, 0, 0, 0, 1e-3, 1.0]       # wy = 1 + 1e-3 z : g turns at z = 500
    p = zcal.validate_record(zcal.record_from_mapping(turn, layout=zcal.LAYOUT_FIT_3D, origin=zcal.ORIGIN_FILE))
    assert any("monotone only" in q for q in p), p


