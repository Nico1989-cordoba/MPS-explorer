        f2026 = os.path.join(tmp, "stack_3d_calib.yaml")
        with open(f2026, "w", encoding="utf-8") as h:
            yaml.safe_dump(cal, h)
        f2023 = os.path.join(tmp, "old_3d_calib.yaml")
        with open(f2023, "w", encoding="utf-8") as h:
            yaml.safe_dump({"X Coefficients": cal["X Coefficients"], "Y Coefficients": cal["Y Coefficients"]}, h)
        thunder = os.path.join(tmp, "stack_thunder")
        with open(thunder, "w", encoding="utf-8") as h:
            h.write("!!cz.cuni.lf1.lge.ThunderSTORM.calibration.PolynomialCalibration {a1: 1.9E-6, a2: 2.2E-6, "
                    "angle: 0.45, b1: 1.2, b2: 1.3, c1: -216.0, c2: 274.2, d1: 0.0, d2: 0.0, w01: 1.0, w02: 1.0}\n")
