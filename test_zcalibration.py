    # frame bounds keep frames 10..70 of 81 one-frame steps: steps 10..70, stage +750..-750
    rec = zcal.record_from_mapping(calibration_dict(81, 25.0, 0.79, **{"Frame bounds": [10, 70]}),
                                   layout=zcal.LAYOUT_FIT_3D, origin=zcal.ORIGIN_FILE)
