def test_classification() -> None:
    print("\n5. MEMBRANE OR INTERIOR")
    shape = (80, 80)
    centre, radius = (40.0, 40.0), 12.0
    mask = ax.build_mask(disc_image(shape, centre, radius), centre, radius,
                         PIXEL_NM, threshold=half_level(),
                         smooth_sigma_px=0.0)

    def margin():
        # Depths of 10, 2, 0.5 px inside, 2 px outside, and one off the
        # region altogether (the edge is 12 px from the centre).
        cols = centre[0] + np.array([2.0, 10.0, 11.5, 14.0, 300.0])
        rows = np.full(cols.shape, centre[1])
        none = ax.classify(mask, cols, rows, margin_nm=0.0)
        assert list(none.labels) == [ax.LABEL_INTERIOR, ax.LABEL_INTERIOR,
                                     ax.LABEL_INTERIOR, ax.LABEL_MEMBRANE,
                                     ax.LABEL_OUTSIDE], none.labels
        wide = ax.classify(mask, cols, rows, margin_nm=150.0)
        assert list(wide.labels[:4]) == [ax.LABEL_INTERIOR, ax.LABEL_INTERIOR,
                                         ax.LABEL_MEMBRANE, ax.LABEL_MEMBRANE]
        assert wide.fraction_interior == 0.5, wide.fraction_interior
        return "a 150 nm margin moves the 56 nm-deep one to membrane"

    def ring_on_the_edge():
        rng = np.random.default_rng(5)
        angle = rng.uniform(0, 2 * np.pi, 5000)
        r = radius + rng.normal(0, 0.3, angle.size)
        cols = centre[0] + r * np.cos(angle)
        rows = centre[1] + r * np.sin(angle)
        result = ax.classify(mask, cols, rows, margin_nm=0.0)
        assert 0.35 < result.fraction_interior < 0.65, result.fraction_interior
        wide = ax.classify(mask, cols, rows, margin_nm=150.0)
        assert wide.fraction_interior < 0.05, wide.fraction_interior
        return (f"a ring on the edge: {result.fraction_interior:.0%} interior "
                f"without a margin, {wide.fraction_interior:.0%} with 150 nm")

    def summary():
        cols = centre[0] + np.array([2.0, 14.0])
        rows = np.full(cols.shape, centre[1])
        result = ax.classify(mask, cols, rows, 0.0)
        reg = ax.ImageRegistration(shift_px=(1.0, -2.0), source="manual")
        kwargs = dict(localizations="a.hdf5", tubulin="t.tif", reference="",
                      registration_file="", roi="none", pixel_size_nm=PIXEL_NM,
                      offset_px=(0.0, 0.0), registration=reg, mask=mask,
                      result=result)
        without = ax.summary_row(cluster_result=None, **kwargs)
        with_clusters = ax.summary_row(cluster_result=result, **kwargs)
        assert list(without) == list(with_clusters)
        assert without["n_clusters"] is None
        assert with_clusters["n_clusters_interior"] == 1
        assert without["shift_x_nm"] == 113.0 and without["shift_y_nm"] == -226.0
        assert without["n_interior"] == 1 and without["fraction_interior"] == 0.5
        return f"{len(without)} columns, the same with or without clusters"

    check("the margin", margin)
    check("a spectrin ring on a blurred edge", ring_on_the_edge)
    check("the summary row", summary)


