def check(name: str, fn) -> None:
    global PASSED, FAILED
    try:
        detail = fn()
    except Exception:  # noqa: BLE001 - a harness
        FAILED += 1
        print(f"  FAIL  {name}")
        for line in traceback.format_exc().strip().splitlines()[-3:]:
            print(f"        {line}")
        return
    PASSED += 1
    print(f"  ok    {name}" + (f"   [{detail}]" if detail else ""))


def expect_error(fn, *words: str) -> str:
    try:
        fn()
    except ValueError as error:
        text = str(error)
        for word in words:
            assert word in text, (word, text)
        return text
    raise AssertionError("no error raised")


def movie_info(region: str = "224-222-274-310", binning: object = 2,
               movie: str = "movie.ome.tif") -> List[dict]:
    return [{"Micro-Manager Metadata": {"ROI": region, "Binning": binning},
             "File": movie},
            {"Generated by": "Picasso Localize", "Pixelsize": PIXEL_NM}]


def ring_field(rng: np.random.Generator, shape: Tuple[int, int],
               n_rings: int = 14) -> List[Tuple[float, float, float]]:
    rows, cols = shape
    rings: List[Tuple[float, float, float]] = []
    while len(rings) < n_rings:
        r = rng.uniform(4, 10)
        cx, cy = rng.uniform(r + 3, cols - r - 3), rng.uniform(r + 3, rows - r - 3)
        if all(math.hypot(cx - a, cy - b) > r + s + 3 for a, b, s in rings):
            rings.append((cx, cy, r))
    return rings


def sample_rings(rng: np.random.Generator, rings, per_ring: int = 3000
                 ) -> Tuple[np.ndarray, np.ndarray]:
    xs, ys = [], []
    for cx, cy, r in rings:
        angle = rng.uniform(0, 2 * np.pi, per_ring)
        radial = r + rng.normal(0, 0.25, per_ring)
        xs.append(cx + radial * np.cos(angle))
        ys.append(cy + radial * np.sin(angle))
    return np.concatenate(xs), np.concatenate(ys)


def widefield_of(rng, rings, shape, shift=(0.0, 0.0), noise=3.0):
    """A widefield image of the rings, as seen ``shift`` px away."""
    x, y = sample_rings(rng, rings, per_ring=6000)
    counts = ax.render_counts(x + shift[0], y + shift[1], shape)
    image = ndimage.gaussian_filter(counts, 1.3) * 5.0 + 100.0
    return image + rng.normal(0, noise, shape)


def disc_image(shape, centre, radius, value=100.0, background=10.0):
    """
    A disc with a one-pixel linear edge, so that its half-intensity
    contour is the circle of ``radius`` at every angle. A hard-edged disc
    is a staircase, half a pixel inside the circle on the diagonals.
    """
    rows, cols = shape
    rr, cc = np.mgrid[0:rows, 0:cols]
    d = np.hypot(cc - centre[0], rr - centre[1])
    weight = np.clip(0.5 + (radius - d), 0.0, 1.0)
    return background + (value - background) * weight


def half_level(value=100.0, background=10.0):
    return 0.5 * (value + background)


