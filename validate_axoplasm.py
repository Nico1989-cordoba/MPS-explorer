def test_placing() -> None:
    print("\n2. PLACING THE IMAGE ON THE LOCALIZATIONS")

    def image_with(region, binning=2, pixel=None):
        return ax.WidefieldImage(
            path="tub.tif", image=np.zeros((10, 10)), n_planes=1,
            camera_region=region, binning=binning, pixel_size_nm=pixel,
            acquired=None)

    def offsets():
        (dx, dy), notes = ax.camera_offset(
            image_with((221, 224, 10, 10)), movie_info(), PIXEL_NM)
        assert (dx, dy) == (3.0, -2.0) and not notes, (dx, dy, notes)
        return "movie at (224, 222), image at (221, 224): (+3, -2) px"

    def refusals():
        expect_error(lambda: ax.camera_offset(
            image_with((0, 0, 10, 10), binning=1), movie_info(), PIXEL_NM),
            "binning 1", "binning 2")
        expect_error(lambda: ax.camera_offset(
            image_with((0, 0, 10, 10), pixel=65.0), movie_info(), PIXEL_NM),
            "65", "113")
        return "another binning or pixel size"

    def unknown_region():
        (dx, dy), notes = ax.camera_offset(image_with(None), movie_info(),
                                           PIXEL_NM)
        assert (dx, dy) == (0.0, 0.0) and notes
        (dx, dy), notes = ax.camera_offset(image_with((0, 0, 10, 10)),
                                           [{"Pixelsize": 113}], PIXEL_NM)
        assert (dx, dy) == (0.0, 0.0) and "localization movie" in notes[0]
        return None

    def geometry():
        region, binning, _time, movie = ax.movie_geometry(movie_info(
            binning="2x2"))
        assert region == (224, 222, 274, 310) and binning == 2
        assert movie == "movie.ome.tif"
        assert ax.movie_geometry([{"Pixelsize": 113}]) == (None, None, None,
                                                            None)
        return None

    def pixel_centres():
        # Picasso puts an emitter centred on pixel c at x = c.
        counts = ax.render_counts(np.array([11.0, 11.49, 11.51, -0.49]),
                                  np.array([7.0, 7.0, 7.0, 0.0]), (10, 20))
        assert counts[7, 11] == 2 and counts[7, 12] == 1 and counts[0, 0] == 1
        assert counts.sum() == 4
        return "pixel c spans [c - 0.5, c + 0.5)"

    check("camera regions give the offset", offsets)
    check("another binning or pixel size is refused", refusals)
    check("an unknown region is assumed, and said", unknown_region)
    check("the movie's geometry from Picasso's metadata", geometry)
    check("pixel centres", pixel_centres)


# ========================================================= registration
def test_registration() -> None:
    print("\n3. REGISTERING TO A WIDEFIELD IMAGE OF THE SAME PROTEIN")
    shape = (180, 160)

    def known_shift():
        rng = np.random.default_rng(1)
        rings = ring_field(rng, shape)
        true = (-2.05, 5.55)
        image = widefield_of(rng, rings, shape, shift=true)
        x, y = sample_rings(rng, rings)
        reg = ax.measure_shift(image, x, y)
        err = np.hypot(reg.shift_px[0] - true[0], reg.shift_px[1] - true[1])
        assert err < 0.15, (reg.shift_px, true)
        assert not reg.warnings, reg.warnings
        assert reg.peak > reg.zero and reg.runner_up < 0.5 * reg.peak
        assert reg.score > ax.MIN_REGISTRATION_SCORE, reg.score
        # The shift is what the localizations need: moved by it, they
        # correlate with the image better than by its opposite.
        moved = ax.measure_shift(image, x + reg.shift_px[0],
                                 y + reg.shift_px[1])
        assert np.hypot(*moved.shift_px) < 0.15, moved.shift_px
        return (f"({reg.shift_px[0]:+.2f}, {reg.shift_px[1]:+.2f}) px for "
                f"({true[0]:+.2f}, {true[1]:+.2f}); peak {reg.peak:.2f}, "
                f"unshifted {reg.zero:.2f}, score {reg.score:.0f}")

    def beyond_the_search():
        rng = np.random.default_rng(2)
        rings = ring_field(rng, shape)
        image = widefield_of(rng, rings, shape, shift=(26.0, 0.0))
        x, y = sample_rings(rng, rings)
        reg = ax.measure_shift(image, x, y, max_shift_px=20)
        # A spurious shift inside the search wins; it must not pass as a
        # registration.
        assert reg.warnings, (reg.shift_px, reg.score, reg.runner_up)
        return "flagged: " + reg.warnings[0][:50] + "..."

    def ambiguous_lattice():
        # Identical rings on a regular grid: a shift of one period fits
        # as well as none.
        rng = np.random.default_rng(3)
        rings = [(20.0 + 20 * i, 20.0 + 20 * j, 6.0)
                 for i in range(7) for j in range(8)]
        image = widefield_of(rng, rings, shape)
        x, y = sample_rings(rng, rings, per_ring=800)
        reg = ax.measure_shift(image, x, y, max_shift_px=25)
        assert any("ambiguous" in w for w in reg.warnings), reg.warnings
        return None

    def off_the_image():
        expect_error(lambda: ax.measure_shift(
            np.zeros(shape), np.array([500.0, 600.0]),
            np.array([500.0, 600.0])), "do not fall on")
        return None

    check("a known shift is recovered, with its sign", known_shift)
    check("a shift beyond the search is flagged", beyond_the_search)
    check("a periodic field is flagged as ambiguous", ambiguous_lattice)
    check("localizations off the image are refused", off_the_image)


# ================================================================ mask
def test_mask() -> None:
    print("\n4. THE AXOPLASM MASK")
    shape = (80, 80)

    def otsu():
        rng = np.random.default_rng(4)
        values = np.concatenate([rng.normal(100, 5, 4000),
                                 rng.normal(200, 8, 2500)])
        t = ax.otsu_threshold(values)
        assert 115 < t < 185, t
        # Against a brute-force search over the same histogram.
        hist, edges = np.histogram(values, bins=256)
        centres = 0.5 * (edges[:-1] + edges[1:])
        best, best_t = -1.0, None
        for k in range(1, 256):
            w0, w1 = hist[:k].sum(), hist[k:].sum()
            if w0 == 0 or w1 == 0:
                continue
            m0 = (hist[:k] * centres[:k]).sum() / w0
            m1 = (hist[k:] * centres[k:]).sum() / w1
            score = w0 * w1 * (m0 - m1) ** 2
            if score > best:
                best, best_t = score, edges[k]
        # A flat maximum may be resolved at another bin than the first:
        # compare the variance reached, not the position.
        k = int(np.searchsorted(edges, t))
        w0, w1 = hist[:k].sum(), hist[k:].sum()
        m0 = (hist[:k] * centres[:k]).sum() / w0
        m1 = (hist[k:] * centres[k:]).sum() / w1
        assert abs(w0 * w1 * (m0 - m1) ** 2 / best - 1) < 1e-6, (t, best_t)
        assert ax.otsu_threshold(np.full(10, 7.0)) == 7.0
        # Two levels only: the middle of the gap, not just above the lower.
        two = ax.otsu_threshold(np.array([10.0] * 50 + [100.0] * 20))
        assert 50 < two < 60, two
        return f"{t:.1f} between modes at 100 and 200; {two:.1f} for 10 and 100"

    def disc_and_distances():
        centre, radius = (40.0, 40.0), 12.0
        image = disc_image(shape, centre, radius)
        mask = ax.build_mask(image, centre, radius, PIXEL_NM,
                             threshold=half_level(), smooth_sigma_px=0.0)
        truth = math.pi * (radius * PIXEL_NM / 1000) ** 2
        assert abs(mask.area_um2 / truth - 1) < 0.03, (mask.area_um2, truth)
        assert not mask.warnings, mask.warnings
        angles = np.deg2rad([0, 30, 45, 60, 90, 135, 200, 315])
        worst = 0.0
        for depth in (-8.0, -3.0, 0.0, 6.0, 12.0):
            r = radius - depth
            cols = centre[0] + r * np.cos(angles)
            rows = centre[1] + r * np.sin(angles)
            got = mask.distance_at(cols, rows)
            worst = max(worst, float(np.max(np.abs(got - depth * PIXEL_NM))))
        # EDT on a grid 4x finer than the camera, and a bilinear contour:
        # a third of a camera pixel.
        assert worst < 0.35 * PIXEL_NM, worst
        automatic = ax.build_mask(image, centre, radius, PIXEL_NM,
                                  smooth_sigma_px=0.0)
        assert abs(automatic.area_um2 / truth - 1) < 0.1, automatic.area_um2
        return (f"area within 3%; distances within {worst:.0f} nm at any "
                f"angle; Otsu's mask within 10%")

    def neighbour_left_out():
        # A dim axon, and a brighter neighbour 4 px from its edge.
        centre, radius = (30.0, 40.0), 8.0
        image = disc_image(shape, centre, radius, value=60.0) + \
            disc_image(shape, (47.0, 40.0), 5.0, value=150.0, background=0.0)
        above_axon = ax.build_mask(image, centre, radius, PIXEL_NM,
                                   threshold=100.0, smooth_sigma_px=0.0)
        # Only the neighbour clears the cut, and it is not over the axon.
        assert above_axon.empty, above_axon.area_um2
        assert any("No axoplasm" in w for w in above_axon.warnings)
        manual = ax.build_mask(image, centre, radius, PIXEL_NM,
                               threshold=35.0, smooth_sigma_px=0.0)
        truth = math.pi * (radius * PIXEL_NM / 1000) ** 2
        assert manual.threshold_source == "manual"
        assert abs(manual.area_um2 / truth - 1) < 0.05, manual.area_um2
        # A point on the neighbour, inside the analysed region.
        assert manual.distance_at(np.array([44.0]), np.array([40.0]))[0] < 0
        return "the neighbour is never taken for the axon"

    def holes_filled():
        # A dark centre: the region over the axon is taken instead of the
        # centre's, with a warning, and its hole is filled.
        centre, radius = (40.0, 40.0), 12.0
        image = disc_image(shape, centre, radius) - \
            disc_image(shape, centre, 4.0, value=90.0, background=0.0)
        mask = ax.build_mask(image, centre, radius, PIXEL_NM,
                             threshold=half_level(), smooth_sigma_px=0.0)
        assert any("centre is below" in w for w in mask.warnings), mask.warnings
        assert mask.distance_at(np.array([40.0]), np.array([40.0]))[0] > 0
        return None

    def nothing_over_the_threshold():
        centre, radius = (40.0, 40.0), 12.0
        image = disc_image(shape, centre, radius)
        mask = ax.build_mask(image, centre, radius, PIXEL_NM,
                             threshold=1000.0, smooth_sigma_px=0.0)
        assert mask.empty and any("No axoplasm" in w for w in mask.warnings)
        result = ax.classify(mask, np.array([40.0, 60.0]),
                             np.array([40.0, 40.0]), 0.0)
        assert list(result.labels) == [ax.LABEL_MEMBRANE] * 2
        assert np.all(np.isneginf(result.distance_nm))
        return None

    def area_warnings():
        centre = (40.0, 40.0)
        image = disc_image(shape, centre, 14.0)
        big = ax.build_mask(image, centre, 6.0, PIXEL_NM, smooth_sigma_px=0.0)
        assert any("times the area" in w for w in big.warnings), big.warnings
        small = ax.build_mask(disc_image(shape, centre, 5.0), centre, 12.0,
                              PIXEL_NM, smooth_sigma_px=0.0)
        assert any("only" in w for w in small.warnings), small.warnings
        return None

    def mask_reaches_the_region_edge():
        centre, radius = (40.0, 40.0), 10.0
        image = np.full(shape, 100.0)
        image[:, :20] = 10.0
        mask = ax.build_mask(image, centre, radius, PIXEL_NM,
                             threshold=50.0, smooth_sigma_px=0.0)
        assert any("edge of the analysed region" in w
                   for w in mask.warnings), mask.warnings
        return None

    def axon_outside():
        expect_error(lambda: ax.build_mask(np.zeros(shape), (500.0, 500.0),
                                           5.0, PIXEL_NM), "outside")
        return None

    check("Otsu's threshold", otsu)
    check("a disc: area and signed distances", disc_and_distances)
    check("a brighter neighbour", neighbour_left_out)
    check("holes are filled", holes_filled)
    check("nothing over the threshold", nothing_over_the_threshold)
    check("a mask much larger or smaller than the ring", area_warnings)
    check("a mask cut by the region's edge", mask_reaches_the_region_edge)
    check("an axon off the image", axon_outside)


