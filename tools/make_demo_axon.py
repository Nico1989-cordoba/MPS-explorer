# -*- coding: utf-8 -*-
"""
Write the SIMULATED example axon that the beginner tour opens (Help -> "Open the example axon (simulated)").

    venv/Scripts/python.exe tools/make_demo_axon.py [--out examples/demo_axon]

What it writes
--------------
``demo_axon_simulated.hdf5`` and its Picasso sidecar ``demo_axon_simulated.yaml``: one picked axon in the Picasso
format the main window reads (x, y and the precisions in camera pixels, z in nanometres, a pixel size of 130 nm in
the YAML). Nothing in it was measured: the localizations come from this project's own simulator,
``tools.mps_simulate_axon.simulate_axon``, through ``batch_columns.write_simulated_input`` - the same call, contour,
seed and axial-leak scale as the "viable" case of the Z-quality demo (``tools.mps_zquality_window.DEMO_CASES``:
circle contour, seed 39, axial leak x 0.3), which is also axon A of the UI golden (``golden_ui_stage2.AXONS``).

Why a simulated axon
--------------------
So that a beginner can follow the tour on the real program's real output without any data of their own, and so that
every example number the tour quotes comes from a file anyone can regenerate - never from unpublished measurements.
The tour labels each of those numbers "simulated example".

The YAML says SIMULATED in a comment on its first line, and the file name says it too.

@author: Nicolas (ngomez) + Claude
"""

from __future__ import annotations

import argparse
import io
import os
import sys
from typing import List, Optional

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if REPO not in sys.path:
    sys.path.insert(0, REPO)

# The recipe, written once: the README beside the file and the tour quote these.
CONTOUR = "circle"
SEED = 39
AXIAL_LEAK_SCALE = 0.3
PIXEL_NM = 130.0
STEM = "demo_axon_simulated"
DEFAULT_OUT = os.path.join(REPO, "examples", "demo_axon")


def demo_path(folder: str = DEFAULT_OUT) -> str:
    """Where the example axon's HDF5 is (it may not exist yet)."""
    return os.path.join(folder, STEM + ".hdf5")


def write_demo(folder: str = DEFAULT_OUT) -> str:
    """Simulate the axon and write it as Picasso HDF5 + YAML under ``folder``. Returns the HDF5 path."""
    import h5py

    import batch_columns as bc

    os.makedirs(folder, exist_ok=True)
    # In memory: the simulator's NPZ never touches the disk.
    buffer = io.BytesIO()
    bc.write_simulated_input(buffer, CONTOUR, SEED, AXIAL_LEAK_SCALE)  # type: ignore[arg-type]
    buffer.seek(0)
    with np.load(buffer) as d:
        x, y, z = (np.asarray(d[q], float) for q in ("x", "y", "z"))
        frame = np.asarray(d["frame"], np.int64)
        lp, lpz = np.asarray(d["lp"], float), np.asarray(d["lpz"], float)
        n_frames = int(np.asarray(d["n_frames"]).reshape(-1)[0])
    rows = np.zeros(x.size, dtype=[
        ("frame", "u4"), ("x", "f4"), ("y", "f4"), ("z", "f4"),
        ("photons", "f4"), ("sx", "f4"), ("sy", "f4"), ("bg", "f4"),
        ("lpx", "f4"), ("lpy", "f4"), ("lpz", "f4")])
    rows["frame"] = frame
    rows["x"] = x / PIXEL_NM
    rows["y"] = y / PIXEL_NM
    rows["z"] = z
    # Not simulated: constant placeholders for the columns Picasso always writes. Nothing in the tour reads them.
    rows["photons"] = 3000.0
    rows["sx"] = rows["sy"] = 1.0
    rows["bg"] = 50.0
    rows["lpx"] = rows["lpy"] = lp / PIXEL_NM
    rows["lpz"] = lpz
    path = demo_path(folder)
    with h5py.File(path, "w") as handle:
        handle.create_dataset("locs", data=rows)
    width = int(np.ceil(max(float(np.max(x)), float(np.max(y))) / PIXEL_NM)) + 1
    with open(os.path.splitext(path)[0] + ".yaml", "w", encoding="utf-8", newline="\n") as f:
        f.write(f"# SIMULATED axon (not a measurement): tools/make_demo_axon.py, simulate_axon contour={CONTOUR}, "
                f"seed={SEED}, axial leak x{AXIAL_LEAK_SCALE:g}\n"
                f"Frames: {n_frames}\nWidth: {width}\nHeight: {width}\n---\n"
                f"Generated by: MPS Explorer simulator (tools/make_demo_axon.py)\nPixelsize: {PIXEL_NM:g}\n")
    return path


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args(argv)
    path = write_demo(args.out)
    print(f"written {path} ({os.path.getsize(path):,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
