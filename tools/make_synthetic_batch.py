# -*- coding: utf-8 -*-
"""
Write a SIMULATED batch of picked axons, as Picasso HDF5 + YAML, in the folder layout of the user's measurements.

    venv/Scripts/python.exe -m tools.make_synthetic_batch --out <folder> [--rois 2 --axons 3 --pixel 113]

What it writes
--------------
``<out>/<sample>/ROI n/Axon m/<date>_bIIspt_AF647_<KO|WT>_<movie>_MMStack.ome_locs_filter_picked_Axon<m>.hdf5`` and its
YAML, for each genotype, ROI and axon: the naming convention of the user's picks (labelled protein, secondary,
genotype, "picked", axon number; no animal). Every file is one axon of this project's own simulator
(``batch_columns.write_simulated_input`` -> ``tools.mps_simulate_axon.simulate_axon``, the same recipe as
``tools/make_demo_axon.py``), shifted laterally by a different whole number of camera pixels so that no two files
have the same bytes. There is no genotype effect: the launcher does no inference without the animal.

The YAML says SIMULATED on its first line. It carries a localize step (pixel size, frames) and a pick step, the two
steps a real pick has; ``write_axon`` can also drop the YAML, embed the metadata, drop z, write x,y in nm or change
the pixel size, to build the broken cases the launcher's pre-checks must catch (tests only; nothing here reads data).

@author: Nicolas (ngomez) + Claude
"""

from __future__ import annotations

import argparse
import io
import json
import os
import sys
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Sequence, Tuple

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if REPO not in sys.path:
    sys.path.insert(0, REPO)

# The recipe of tools/make_demo_axon.py (the "viable" case of the Z-quality demo). [own sim]
CONTOUR = "circle"
SEED = 39
AXIAL_LEAK_SCALE = 0.3
FRAMES = 60000                                     # [the user's acquisitions: 60 000 frames]
DATE = "26.11.07"                                  # [ad hoc: an invented date in the user's format]
NAME = "{date}_bIIspt_AF647_{genotype}_{movie}_MMStack.ome_locs_filter_picked_Axon{axon}.hdf5"

_CACHE: Dict[Tuple[str, int, float], Dict[str, Any]] = {}


def simulate(contour: str = CONTOUR, seed: int = SEED, leak: float = AXIAL_LEAK_SCALE) -> Dict[str, Any]:
    """One simulated axon in nm (x, y, z, frame, lp, lpz, n_frames), cached per recipe."""
    key = (str(contour), int(seed), float(leak))
    if key not in _CACHE:
        import batch_columns as bc

        buffer = io.BytesIO()
        bc.write_simulated_input(buffer, contour, int(seed), float(leak))  # type: ignore[arg-type]
        buffer.seek(0)
        with np.load(buffer) as d:
            _CACHE[key] = {q: np.asarray(d[q]) for q in ("x", "y", "z", "frame", "lp", "lpz")}
            _CACHE[key]["n_frames"] = int(np.asarray(d["n_frames"]).reshape(-1)[0])
    return _CACHE[key]


@dataclass
class AxonFile:
    """How to write one file (defaults: a clean pick)."""

    pixel_nm: float = 130.0
    shift_px: float = 0.0
    yaml: bool = True                  # write the Picasso YAML sidecar
    embed_metadata: bool = False       # write the metadata into /metadata of the HDF5 too
    yaml_pixel_nm: Optional[float] = None   # the pixel the YAML states (default: pixel_nm)
    frames: Optional[int] = None       # the YAML's Frames (default: FRAMES)
    with_z: bool = True
    xy_in_nm: bool = False             # the broken case: x, y written in nm instead of camera pixels
    z_in_um: bool = False              # the broken case: z written in micrometres
    pick_step: bool = True             # the YAML records a pick step
    contour: str = CONTOUR
    seed: int = SEED


def _yaml_text(spec: AxonFile, width: int, frames: int) -> str:
    pixel = spec.pixel_nm if spec.yaml_pixel_nm is None else spec.yaml_pixel_nm
    text = (f"# SIMULATED axon (not a measurement): tools/make_synthetic_batch.py, simulate_axon "
            f"contour={spec.contour}, seed={spec.seed}, axial leak x{AXIAL_LEAK_SCALE:g}\n"
            f"Frames: {frames}\nWidth: {width}\nHeight: {width}\n"
            f"Generated by: MPS Explorer synthetic batch (simulated localize step)\n"
            f"Pixelsize: {pixel:g}\n")
    if spec.pick_step:
        text += "---\nGenerated by: MPS Explorer synthetic batch (simulated pick step)\nPick shape: Circle\n"
    return text


def write_axon(path: str, spec: Optional[AxonFile] = None) -> str:
    """Write one simulated axon at ``path`` (.hdf5) as ``spec`` says. Returns the path."""
    import h5py

    spec = spec or AxonFile()
    sim = simulate(spec.contour, spec.seed)
    pixel = float(spec.pixel_nm)
    x = np.asarray(sim["x"], float) + spec.shift_px * pixel
    y = np.asarray(sim["y"], float)
    fields = [("frame", "u4"), ("x", "f4"), ("y", "f4")]
    if spec.with_z:
        fields.append(("z", "f4"))
    fields += [("photons", "f4"), ("sx", "f4"), ("sy", "f4"), ("bg", "f4"), ("lpx", "f4"), ("lpy", "f4")]
    if spec.with_z:
        fields.append(("lpz", "f4"))
    rows = np.zeros(x.size, dtype=fields)
    rows["frame"] = np.asarray(sim["frame"], np.int64)
    rows["x"] = x if spec.xy_in_nm else x / pixel
    rows["y"] = y if spec.xy_in_nm else y / pixel
    if spec.with_z:
        z = np.asarray(sim["z"], float)
        rows["z"] = z / 1000.0 if spec.z_in_um else z
        rows["lpz"] = np.asarray(sim["lpz"], float)
    # Not simulated: constant placeholders for the columns Picasso always writes.
    rows["photons"] = 3000.0
    rows["sx"] = rows["sy"] = 1.0
    rows["bg"] = 50.0
    rows["lpx"] = rows["lpy"] = np.asarray(sim["lp"], float) / pixel
    frames = int(spec.frames if spec.frames is not None else FRAMES)
    width = int(np.ceil(max(float(np.max(x)), float(np.max(y))) / pixel)) + 1
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with h5py.File(path, "w") as handle:
        handle.create_dataset("locs", data=rows)
        if spec.embed_metadata:
            import yaml  # type: ignore[import-untyped, unused-ignore]
            docs = [d for d in yaml.safe_load_all(_yaml_text(spec, width, frames)) if isinstance(d, dict)]
            handle.create_dataset("metadata", data=json.dumps(docs))
    if spec.yaml:
        with open(os.path.splitext(path)[0] + ".yaml", "w", encoding="utf-8", newline="\n") as f:
            f.write(_yaml_text(spec, width, frames))
    return path


def file_name(genotype: str, roi: int, axon: int, date: str = DATE) -> str:
    """The user's convention; the movie number is the ROI's, so two ROIs never share a file name."""
    return NAME.format(date=date, genotype=genotype, movie=roi, axon=axon)


def make_batch(root: str, genotypes: Sequence[str] = ("KO", "WT"), rois: int = 2, axons: int = 3,
               pixel_nm: float = 130.0) -> List[str]:
    """A clean simulated batch under ``root``: one sample folder per genotype, ``rois`` x ``axons`` picks each."""
    paths: List[str] = []
    shift = 0
    for g_index, genotype in enumerate(genotypes):
        sample = f"nervio_{g_index + 1}"
        for r in range(1, rois + 1):
            for a in range(1, axons + 1):
                shift += 1
                path = os.path.join(root, sample, f"ROI {r}", f"Axon {a}", file_name(genotype, r, a))
                paths.append(write_axon(path, AxonFile(pixel_nm=pixel_nm, shift_px=float(shift))))
    return paths


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Write a simulated batch of picked axons (Picasso HDF5 + YAML).")
    ap.add_argument("--out", required=True)
    ap.add_argument("--rois", type=int, default=2)
    ap.add_argument("--axons", type=int, default=3)
    ap.add_argument("--pixel", type=float, default=130.0)
    args = ap.parse_args(argv)
    paths = make_batch(args.out, rois=args.rois, axons=args.axons, pixel_nm=args.pixel)
    print(f"{len(paths)} simulated axons written under {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
