def check(name: str, fn) -> None:
    global PASSED, FAILED
    try:
        detail = fn()
    except Exception as error:  # noqa: BLE001 - a harness, it reports everything
        FAILED += 1
        print(f"  FAIL  {name}")
        for line in traceback.format_exc().strip().splitlines()[-3:]:
            print(f"        {line}")
        return
    PASSED += 1
    print(f"  ok    {name}" + (f"   [{detail}]" if detail else ""))


# --------------------------------------------------------------- helpers
def write_hdf5(
    path: str,
    n: int = 50,
    *,
    with_z: bool = True,
    embedded_pixel_size: float | None = None,
    sidecar_pixel_size: float | None = None,
    locs_key: str = "locs",
) -> None:
    """A minimal Picasso-shaped file, with the metadata placed as asked."""
    import h5py as h5

    rng = np.random.default_rng(0)
    fields = [
        ("frame", np.uint32, rng.integers(0, 1000, n)),
        ("x", np.float32, rng.uniform(10, 20, n)),
        ("y", np.float32, rng.uniform(10, 20, n)),
        ("photons", np.float32, rng.uniform(500, 5000, n)),
        ("lpx", np.float32, np.full(n, 0.10)),
        ("lpy", np.float32, np.full(n, 0.10)),
    ]
    if with_z:
        fields += [
            ("z", np.float32, rng.uniform(-100, 100, n)),
            ("lpz", np.float32, np.full(n, 45.0)),
        ]
    dtype = np.dtype([(name, kind) for name, kind, _ in fields])
    table = np.zeros(n, dtype=dtype)
    for name, _kind, values in fields:
        table[name] = values

    with h5.File(path, "w") as handle:
        handle.create_dataset(locs_key, data=table)
        if embedded_pixel_size is not None:
            info = [
                {"Frames": 1000, "Width": 256, "Height": 256},
                {
                    "Generated by": "Picasso v0.11.1 Localize",
                    "Pixelsize": embedded_pixel_size,
                    "Box Size": 13,
                    "Fit method": "LQ, Gaussian",
                },
            ]
            handle.create_dataset("metadata", data=json.dumps(info))

    if sidecar_pixel_size is not None:
        with open(
            os.path.splitext(path)[0] + ".yaml", "w", encoding="utf-8"
        ) as handle:
            handle.write("Frames: 1000\nWidth: 256\nHeight: 256\n---\n")
            handle.write("Generated by: Picasso v0.9.10 Localize\n")
            handle.write(f"Pixelsize: {sidecar_pixel_size}\nBox Size: 9\n")


def find_real_axon() -> str | None:
    import glob

    for pattern in ("ROI 1/*.hdf5", "ROI 1/*/*.hdf5", "ROI 2/*.hdf5"):
        hits = [
            f
            for f in glob.glob(os.path.join(DATA_ROOT, pattern))
            if "axon" in os.path.basename(f).lower()
        ]
        if hits:
            return sorted(hits)[0]
    return None


# ================================================== 1. metadata reading
def test_metadata() -> None:
    print("\n1. METADATA CHAIN")

    def newest_wins():
        info = [{"Pixelsize": 133}, {"Pixelsize": 113}]
        assert mps_metadata.pixel_size_nm(info) == 113.0
        return "later step overrides earlier"

    def falsy_is_found():
        # Picasso's own get_from_metadata uses `if val := inf.get(key)`,
        # so it would skip a 0 and keep searching. This must not.
        info = [{"Box Size": 9}, {"Box Size": 0}]
        assert mps_metadata.get_value(info, "Box Size") == 0
        return "Box Size: 0 returned, not skipped"

    def explicit_null_skipped():
        # Picasso writes `lpz: null` in a Filter step to mean "not
        # applied". That must fall through to an older real value.
        info = [{"lpz": [0.0, 0.15]}, {"Generated by": "Filter", "lpz": None}]
        assert mps_metadata.get_value(info, "lpz") == [0.0, 0.15]
        return "null falls through"

    def missing_is_default():
        assert mps_metadata.get_value([{"a": 1}], "b", default=7) == 7
        assert mps_metadata.pixel_size_nm([]) is None
        return None

    def step_lookup():
        info = [
            {"Generated by": "Picasso v0.9.10 Localize", "Box Size": 9},
            {"Generated by": "Picasso v0.9.10 Filter", "lpx": [0, 0.15]},
        ]
        assert mps_metadata.step_containing(info, "Localize")["Box Size"] == 9
        assert mps_metadata.step_containing(info, "filter") is not None
        assert mps_metadata.step_containing(info, "Average") is None
        return "case-insensitive substring"

    def bulky_stripped():
        info = [{"Micro-Manager Metadata": {"a": 1}, "Pixelsize": 113}]
        out = mps_metadata.strip_bulky(info)
        assert out == [{"Pixelsize": 113}]
        return None

    check("newest step wins", newest_wins)
    check("a falsy value is returned, not skipped", falsy_is_found)
    check("an explicit null falls through", explicit_null_skipped)
    check("missing key gives the default", missing_is_default)
    check("step lookup by name", step_lookup)
    check("Micro-Manager block strippable", bulky_stripped)


# ============================================== 2. where the pixel size comes from
def test_pixel_size_sources() -> None:
    print("\n2. PIXEL SIZE PROVENANCE")
    tmp = tempfile.mkdtemp(prefix="mps_io_")

    def from_sidecar():
        path = os.path.join(tmp, "sidecar.hdf5")
        write_hdf5(path, sidecar_pixel_size=113.0)
        loc = load_localizations(path)
        assert loc.pixel_size_nm == 113.0
        assert loc.pixel_size_source == "yaml"
        return "yaml"

    def from_embedded():
        # The Picasso >= 0.11 case the old loader refused outright.
        path = os.path.join(tmp, "embedded.hdf5")
        write_hdf5(path, embedded_pixel_size=130.0)
        assert not os.path.exists(os.path.splitext(path)[0] + ".yaml")
        loc = load_localizations(path)
        assert loc.pixel_size_nm == 130.0
        assert loc.pixel_size_source == "hdf5"
        assert loc.box_size_px == 13
        return "no sidecar, /metadata used"

    def sidecar_preferred():
        path = os.path.join(tmp, "both.hdf5")
        write_hdf5(path, embedded_pixel_size=130.0, sidecar_pixel_size=113.0)
        loc = load_localizations(path)
        assert loc.pixel_size_nm == 113.0, loc.pixel_size_nm
        return "sidecar beats embedded, as in picasso.io.load_info"

    def override_wins():
        path = os.path.join(tmp, "override.hdf5")
        write_hdf5(path, sidecar_pixel_size=113.0)
        loc = load_localizations(path, pixel_size_nm=160.0)
        assert loc.pixel_size_nm == 160.0
        assert loc.pixel_size_source == "override"
        return None

    def refuses_when_unknown():
        path = os.path.join(tmp, "naked.hdf5")
        write_hdf5(path)
        try:
            load_localizations(path)
        except ValueError as error:
            assert "pixel size" in str(error).lower()
            return "refused, did not default to 133"
        raise AssertionError("loaded a file with no pixel size anywhere")

    def malformed_sidecar_still_scanned():
        path = os.path.join(tmp, "broken.hdf5")
        write_hdf5(path)
        with open(
            os.path.splitext(path)[0] + ".yaml", "w", encoding="utf-8"
        ) as handle:
            handle.write("Pixelsize: 113\n\tthis: [is not, valid yaml\n")
        loc = load_localizations(path)
        assert loc.pixel_size_nm == 113.0
        assert loc.pixel_size_source == "yaml_scan"
        return "fallback line scan"

    def read_pixel_size_helper():
        path = os.path.join(tmp, "helper.hdf5")
        write_hdf5(path, embedded_pixel_size=108.0)
        assert read_pixel_size(path) == 108.0
        return "works without a sidecar now"

    check("sidecar", from_sidecar)
    check("embedded /metadata, no sidecar", from_embedded)
    check("sidecar preferred over embedded", sidecar_preferred)
    check("explicit override wins", override_wins)
    check("refuses when nothing knows it", refuses_when_unknown)
    check("malformed sidecar falls back to a scan", malformed_sidecar_still_scanned)
    check("read_pixel_size()", read_pixel_size_helper)


# ============================================================ 3. units
def test_units() -> None:
    print("\n3. UNITS  (the trap this phase exists to close)")
    tmp = tempfile.mkdtemp(prefix="mps_io_u_")
    path = os.path.join(tmp, "units.hdf5")
    write_hdf5(path, sidecar_pixel_size=100.0)
    loc = load_localizations(path)

    def xy_scaled():
        assert np.allclose(loc.x_nm, np.asarray(loc.columns["x"], float) * 100.0)
        return "x * pixel size"

    def lpxy_scaled():
        # 0.10 camera pixels at 100 nm/px = 10 nm.
        assert np.allclose(loc.lpx_nm, 10.0)
        assert np.allclose(loc.lpy_nm, 10.0)
        return "0.10 px -> 10.0 nm"

    def lpz_not_scaled():
        # The whole point: lpz is stored in nm already.
        assert np.allclose(loc.lpz_nm, 45.0), np.median(loc.lpz_nm)
        assert not np.allclose(loc.lpz_nm, 4500.0)
        return "45 nm stays 45 nm, not 4500"

    def z_not_scaled():
        assert np.allclose(loc.z_nm, np.asarray(loc.columns["z"], float))
        return None

    def lateral_mean():
        assert np.allclose(loc.lp_lateral_nm, 10.0)
        return None

    def native_untouched():
        assert np.allclose(loc.columns["lpx"], 0.10)
        return "columns[] keeps native units"

    def failed_fits_marked():
        # A median of 0.10 px, one axis collapsed on four localizations.
        lpx = np.full(200, 0.10)
        lpy = np.full(200, 0.10)
        lpx[0], lpy[1], lpx[2], lpy[3] = 0.0, np.inf, 1e-8, 0.005
        lpx[4] = 0.03                      # bright but genuine: 0.3x
        bad = Localizations(
            x_nm=np.zeros(200), y_nm=np.zeros(200), z_nm=np.zeros(200),
            path="synthetic", fileformat=FORMAT_PICASSO_HDF5,
            pixel_size_nm=100.0, pixel_size_source="test",
            columns={"lpx": lpx, "lpy": lpy},
        )
        lp = bad.lp_lateral_nm
        assert np.all(np.isnan(lp[:4])), lp[:5]
        assert np.all(np.isfinite(lp[4:])), lp[:6]
        assert abs(lp[4] - 6.5) < 1e-9, lp[4]
        # The same tiny precision on a BRIGHT localization is genuine.
        photons = np.linspace(500.0, 1100.0, 200)
        photons[2], photons[3] = 90_000.0, 100.0
        bright = Localizations(
            x_nm=np.zeros(200), y_nm=np.zeros(200), z_nm=np.zeros(200),
            path="synthetic", fileformat=FORMAT_PICASSO_HDF5,
            pixel_size_nm=100.0, pixel_size_source="test",
            columns={"lpx": lpx, "lpy": lpy, "photons": photons},
        )
        lp = bright.lp_lateral_nm
        assert np.isfinite(lp[2]) and np.isnan(lp[3]), lp[:4]
        # And in a file of merged events (Picasso link), on any of them.
        linked = Localizations(
            x_nm=np.zeros(200), y_nm=np.zeros(200), z_nm=np.zeros(200),
            path="synthetic", fileformat=FORMAT_PICASSO_HDF5,
            pixel_size_nm=100.0, pixel_size_source="test",
            columns={"lpx": lpx, "lpy": lpy, "n": np.ones(200)},
        )
        lp = linked.lp_lateral_nm
        assert np.all(np.isfinite(lp[2:])) and np.all(np.isnan(lp[:2])), lp[:5]
        return ("zero, infinite and collapsed fits NaN; a 0.3x one, a bright "
                "one and merged events kept")

    check("x and y scaled to nm", xy_scaled)
    check("lpx and lpy scaled to nm", lpxy_scaled)
    check("lpz NOT scaled", lpz_not_scaled)
    check("z NOT scaled", z_not_scaled)
    check("lp_lateral_nm", lateral_mean)
    check("native columns untouched", native_untouched)
    check("failed fits marked in lp_lateral_nm", failed_fits_marked)


