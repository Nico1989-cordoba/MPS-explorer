# ======================================================== 5. CSV paths
def test_csv() -> None:
    print("\n5. CSV")
    tmp = tempfile.mkdtemp(prefix="mps_io_c_")

    def thunderstorm():
        path = os.path.join(tmp, "ts.csv")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(
                "frame,x [nm],y [nm],z [nm],intensity [photon],"
                "uncertainty_xy [nm]\n"
            )
            # ThunderSTORM numbers frames from 1.
            for i in range(10):
                handle.write(
                    f"{i + 1},{100 + i},{200 + i},{i * 10},900,12.5\n")
        loc = load_localizations(path)
        assert loc.pixel_size_source == "not_applicable"
        assert loc.n == 10
        # Already nm, and no pixel size exists to wrongly apply.
        assert np.allclose(loc.lpx_nm, 12.5)
        assert np.allclose(loc.photons, 900.0)
        # Counted from 0 like Picasso's, while columns[] keeps the file's.
        assert loc.frame is not None and loc.frame[0] == 0, loc.frame
        assert int(np.asarray(loc.columns["frame"])[0]) == 1
        assert loc.subset(np.arange(5, 10)).frame[0] == 5
        # Picasso's own "Export for ThunderSTORM" keeps 0-based frames and
        # writes a background-noise column of zeros.
        exported = os.path.join(tmp, "from_picasso.csv")
        with open(exported, "w", encoding="utf-8") as handle:
            handle.write("id,frame,x [nm],y [nm],z [nm],bkgstd [photon]\n")
            for i in range(10):
                handle.write(f"{i},{i + 12},{100 + i},{200 + i},0,0\n")
        picasso = load_localizations(exported)
        assert picasso.frame is not None and picasso.frame[0] == 12
        return ("aliases resolved, no scaling invented, ThunderSTORM frames "
                "from 0, Picasso's export left alone")

    def custom_three_columns():
        path = os.path.join(tmp, "bare.csv")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write("a,b,c\n1,2,3\n4,5,6\n")
        loc = load_localizations(path, fileformat=FORMAT_CUSTOM_CSV)
        assert loc.n == 2 and loc.z_nm[1] == 6
        return None

    def bare_csv_refused_by_default():
        path = os.path.join(tmp, "bare2.csv")
        with open(path, "w", encoding="utf-8") as handle:
            handle.write("a,b,c\n1,2,3\n")
        try:
            load_localizations(path, fileformat=FORMAT_THUNDERSTORM_CSV)
        except ValueError:
            return "three numeric columns are not assumed to be x,y,z"
        raise AssertionError("guessed coordinates from an arbitrary CSV")

    check("ThunderSTORM csv", thunderstorm)
    check("custom csv, asked for by name", custom_three_columns)
    check("bare csv refused unless asked", bare_csv_refused_by_default)


# ================================================== 6. the real dataset
def test_real_data() -> None:
    print("\n6. REAL DATA")
    path = find_real_axon()
    if path is None:
        print(f"  skip  no axon files under {DATA_ROOT!r}")
        return
    loc = load_localizations(path)

    def columns_present():
        expected = {
            "frame", "x", "y", "photons", "sx", "sy", "bg",
            "lpx", "lpy", "ellipticity", "net_gradient", "z",
            "d_zcalib", "lpz",
        }
        missing = expected - set(loc.columns)
        assert not missing, f"missing {sorted(missing)}"
        return f"{len(loc.columns)} columns, {loc.n:,} locs"

    def metadata_chain():
        assert loc.metadata_source == "yaml"
        assert loc.n_frames == 60000
        assert loc.box_size_px == 9
        assert loc.fit_method and "Gaussian" in loc.fit_method
        assert loc.z_calibration is not None
        assert len(loc.processing_steps) >= 4
        return f"{len(loc.processing_steps)} steps, {loc.n_frames} frames"

    def precisions_sane():
        lpx, lpz = np.median(loc.lpx_nm), np.median(loc.lpz_nm)
        assert 5.0 < lpx < 20.0, f"lpx {lpx}"
        assert 30.0 < lpz < 80.0, f"lpz {lpz}"
        assert lpz > 3 * lpx, "axial precision should be far worse than lateral"
        return f"lpx {lpx:.1f} nm, lpz {lpz:.1f} nm"

    def coordinates_unchanged():
        # The contract every existing caller depends on.
        import h5py as h5

        with h5.File(path, "r") as handle:
            table = handle["locs"]
            x = np.asarray(table["x"], float) * 113.0
            z = np.asarray(table["z"], float)
        assert np.allclose(loc.x_nm, x)
        assert np.allclose(loc.z_nm, z)
        return "identical to the old three-column path"

    def frames_span_movie():
        frame = loc.frame
        assert frame is not None
        assert frame.min() >= 0 and frame.max() < loc.n_frames + 1
        return f"{frame.min()}..{frame.max()}"

    check("every expected column read", columns_present)
    check("metadata chain parsed", metadata_chain)
    check("precisions in range", precisions_sane)
    check("x/y/z identical to before", coordinates_unchanged)
    check("frames within the acquisition", frames_span_movie)


