PIXEL_NM = 130.0


def write_whole_field(path: str, sigma_nm: float, *, n_emitters: int = 600, frames: int = 4000,
                      linked: bool = False, with_frame: bool = True, seed: int = 0) -> None:
    """A Picasso-shaped whole-field file: emitters scattered over a 25 um field, each switching on a few times for a
    few consecutive frames, every localization displaced by N(0, sigma) per axis. Pixel units, YAML sidecar."""
    import h5py as h5

    rng = np.random.default_rng(seed)
    field_nm = 25000.0
    cx = rng.uniform(0, field_nm, n_emitters)
    cy = rng.uniform(0, field_nm, n_emitters)
    fr, xs, ys = [], [], []
    for i in range(n_emitters):
        for _ in range(rng.poisson(3) + 1):
            start = int(rng.integers(0, frames - 10))
            length = int(rng.geometric(0.4))
            for k in range(length):
                fr.append(start + k)
                xs.append(cx[i] + rng.normal(0, sigma_nm))
                ys.append(cy[i] + rng.normal(0, sigma_nm))
    order = np.argsort(fr, kind="stable")
    frame = np.asarray(fr)[order]
    x = np.asarray(xs)[order] / PIXEL_NM
    y = np.asarray(ys)[order] / PIXEL_NM
    fields = [("x", np.float32, x), ("y", np.float32, y),
              ("photons", np.float32, np.full(x.size, 3000.0)),
              ("lpx", np.float32, np.full(x.size, sigma_nm / PIXEL_NM)),
              ("lpy", np.float32, np.full(x.size, sigma_nm / PIXEL_NM))]
    if with_frame:
        fields.insert(0, ("frame", np.uint32, frame))
    if linked:
        fields.append(("len", np.uint32, np.ones(x.size)))
    table = np.zeros(x.size, dtype=np.dtype([(n, k) for n, k, _ in fields]))
    for name, _kind, values in fields:
        table[name] = values
    with h5.File(path, "w") as handle:
        handle.create_dataset("locs", data=table)
    with open(os.path.splitext(path)[0] + ".yaml", "w", encoding="utf-8") as handle:
        handle.write(f"Frames: {frames}\nWidth: 256\nHeight: 256\n---\n")
        handle.write("Generated by: Picasso v0.9.10 Localize\n")
        handle.write(f"Pixelsize: {PIXEL_NM}\nBox Size: 9\n")
        if linked:
            handle.write("---\nGenerated by: Picasso Link\nMax. distance: 3\nMax. dark frames: 1\n")


# ------------------------------------------------------------------------------------------------- 1. formulas
def test_gazal_check() -> None:
    """eps 25, NeNA 12, Alexa 647 in MEA (14) -> 9.6 -> 10: the published MinPoints."""
    n = cp.cycles("Alexa Fluor 647", "MEA")
    assert n == 14
    p = cp.pair_within_probability(25.0, 12.0)
    assert abs(p - (1 - math.exp(-625 / 576))) < 1e-12 and abs(p - 0.662) < 1e-3
    value, raw = cp.derive_min_samples(25.0, 12.0, n)
    assert abs(raw - 9.6) < 0.05, raw
    assert value == cp.GAZAL_MIN_SAMPLES == 10
    # Alexa Fluor 568 in MEA (7 cycles): 1 + 6 x 0.662 = 5.0 -> 5
    assert cp.derive_min_samples(25.0, 12.0, cp.cycles("Alexa Fluor 568", "MEA"))[0] == 5
    # the same eps / sigma ratio keeps the pair probability: eps_2 = 25 x 15 / 12
    eps2 = cp.derive_eps2(25.0, 12.0, 15.0)
    assert abs(eps2 - 31.25) < 1e-12
    assert abs(cp.pair_within_probability(eps2, 15.0) - p) < 1e-12


def test_dye_table_matches_source() -> None:
    """Spot values of Dempsey et al. 2011, Table 1 (mean switching cycles, MEA / betaME)."""
    assert cp.DYE_CYCLES["Alexa Fluor 647"] == {"MEA": 14, "bME": 26}
    assert cp.DYE_CYCLES["Alexa Fluor 568"] == {"MEA": 7, "bME": 52}
    assert cp.DYE_CYCLES["Cy3B"] == {"MEA": 8, "bME": 5}
    assert cp.DYE_CYCLES["Alexa Fluor 488"] == {"MEA": 16, "bME": 139}
    assert len(cp.DYE_CYCLES) == 26
    assert cp.cycles("Alexa Fluor 647", "nonsense") is None and cp.cycles(None, "MEA") is None


def test_expected_count_by_simulation() -> None:
    """The closed form is the mean count DBSCAN tests: simulated molecules of 14 localizations, sigma 12 nm."""
    rng = np.random.default_rng(1)
    counts = []
    for _ in range(3000):
        pts = rng.normal(0, 12.0, size=(14, 2))
        d = np.hypot(*(pts[:, None, :] - pts[None, :, :]).transpose(2, 0, 1))
        counts.append(float(np.mean((d <= 25.0).sum(axis=1))))
    assert abs(np.mean(counts) - cp.expected_core_count(25.0, 12.0, 14)) < 0.1


# ------------------------------------------------------------------------------------------------- 2. pre-fill
def _precision(sigma: float, folder: str, name: str, **kw) -> cp.ChannelPrecision:
    path = os.path.join(folder, name)
    write_whole_field(path, sigma, **kw)
    return cp.precision_from_file(path, found_by="test")


def test_nena_recovers_known_sigma_and_prefills() -> None:
    with tempfile.TemporaryDirectory() as folder:
        p1 = _precision(12.0, folder, "ch1_locs.hdf5", seed=1)
        p2 = _precision(18.0, folder, "ch2_locs.hdf5", seed=2)
        assert p1.measured and p2.measured, (p1.reason, p2.reason)
        assert abs(p1.nena_nm - 12.0) < 1.2, p1.nena_nm
        assert abs(p2.nena_nm - 18.0) < 1.8, p2.nena_nm
        assert p2.source_file == "ch2_locs.hdf5"
        d = cp.derive_channel2(p1, p2, "Alexa Fluor 568", "MEA", eps1_nm=25.0)
        assert d.eps_nm is not None and abs(d.eps_nm - 25.0 * p2.nena_nm / p1.nena_nm) < 1e-9
        assert d.nena1_origin == "measured"
        want, _raw = cp.derive_min_samples(d.eps_nm, p2.nena_nm, 7)
        assert d.min_samples == want
        assert "derived from NeNA" in d.eps_origin and "whole field ch2_locs.hdf5" in d.eps_origin
        assert "Alexa Fluor 568/MEA" in d.min_samples_origin
        assert d.n_loc_mol == 7 and "lower bound" in d.n_loc_mol_origin


def test_channel1_unmeasured_uses_reference_and_says_so() -> None:
    p2 = cp.ChannelPrecision(nena_nm=15.0, n_pairs=900, source_path="/x/ch2.hdf5")
    d = cp.derive_channel2(cp.ChannelPrecision(reason="too few pairs"), p2, "Alexa Fluor 647", "MEA")
