def test_export_columns_and_store() -> None:
    p1 = cp.ChannelPrecision(nena_nm=12.0, n_pairs=900, source_path=os.path.join("C:\\", "private", "ch1.hdf5"))
    p2 = cp.ChannelPrecision(nena_nm=14.0, n_pairs=900, source_path=os.path.join("C:\\", "private", "ch2.hdf5"))
    d = cp.derive_channel2(p1, p2, "Alexa Fluor 647", "bME")
    rec = cp.provenance(d, p1, p2, d.eps_nm, d.min_samples)
    row = cp.export_fields(rec)
    assert list(row) == list(cp.EXPORT_KEYS)
    assert row["nena_b_source_file"] == "ch2.hdf5" and "private" not in json.dumps(row)
    assert row["dye_b"] == "Alexa Fluor 647" and row["buffer_b"] == "bME" and row["n_loc_mol_b"] == 26
    assert row["eps_b_origin"] == "derived" and row["nena_a_origin"] == "measured"
    assert cp.export_fields(None)["nena_b_nm"] == ""

    from tools.mps_settings import MPSSettings
    s = MPSSettings()
    s.channel2_clustering_by_folder = {"k": dict(rec), "bad": {"eps_nm": "x"}}
    s.validate()
    kept = s.channel2_clustering_by_folder["k"]
    assert "bad" not in s.channel2_clustering_by_folder
    assert kept["eps_nm"] == rec["eps_nm"] and kept["dye_b"] == "Alexa Fluor 647"
    assert kept["nena_b_nm"] == 14.0 and kept["eps_b_origin"] == "derived"

    from tools import column_dictionary as cd
    from tools.mps_crosschannel import export_cross_channel
    columns = list(export_cross_channel(None, None))
    for key in cp.EXPORT_KEYS + ("locs_within_eps_a", "locs_within_eps_b"):
        assert key in columns, key
        assert cd.describe(key), key
    assert "locs_per_cell_a" not in columns


def _run_all() -> int:
    failed = 0
    for name, fn in list(globals().items()):
        if name.startswith("test_") and callable(fn):
            try:
                fn()
                print(f"  ok    {name}")
            except Exception as error:  # noqa: BLE001
                failed += 1
                print(f"  FAIL  {name}: {error!r}")
    print(f"{'all passed' if not failed else f'{failed} failed'}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(_run_all())
