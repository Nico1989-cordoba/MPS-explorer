def test_find_whole_field() -> None:
    with tempfile.TemporaryDirectory() as folder:
        roi = os.path.join(folder, "ROI6")
        sel = os.path.join(roi, "Seleccion de axones")
        os.makedirs(sel)
        whole = os.path.join(roi, "ROI6_adducin_locs.hdf5")
        picked = os.path.join(sel, "ROI6_adducin_locs_apicked3.hdf5")
        for p in (whole, picked):
            open(p, "wb").close()
        path, how = cp.find_whole_field(picked)
        assert os.path.normcase(path) == os.path.normcase(whole) and how.startswith("matched by name")
        # a loaded file that is not a picked one is its own whole field
        path, how = cp.find_whole_field(whole)
        assert os.path.normcase(path) == os.path.normcase(whole) and "loaded file itself" in how
        lone = os.path.join(folder, "lonely_picked_7.hdf5")
        open(lone, "wb").close()
        path, how = cp.find_whole_field(lone)
        assert path == "" and how


# ------------------------------------------------------------------------------------------------- 4. origins
def test_edit_becomes_user_and_channel1_never_copied() -> None:
    p1 = cp.ChannelPrecision(nena_nm=12.0, n_pairs=900, source_path="a/ch1.hdf5")
    p2 = cp.ChannelPrecision(nena_nm=16.0, n_pairs=900, source_path="b/ch2.hdf5")
    d = cp.derive_channel2(p1, p2, "Alexa Fluor 568", "MEA", eps1_nm=25.0)
    rec = cp.provenance(d, p1, p2, round(d.eps_nm, 1), d.min_samples)
    assert rec["eps_b_origin"] == rec["min_samples_b_origin"] == cp.ORIGIN_DERIVED
    edited = cp.reconcile(rec, 40.0, d.min_samples)
    assert edited["eps_b_origin"] == cp.ORIGIN_USER and edited["min_samples_b_origin"] == cp.ORIGIN_DERIVED
    edited = cp.reconcile(rec, d.eps_nm, d.min_samples + 3)
    assert edited["min_samples_b_origin"] == cp.ORIGIN_USER
    # channel 2 with a different precision never gets channel 1's 25 / 10
    assert abs(d.eps_nm - 25.0) > 1 and d.min_samples != 10
    # without channel 2's precision nothing is filled, whatever channel 1 has
    empty = cp.derive_channel2(p1, cp.ChannelPrecision(reason="linked"), "Alexa Fluor 647", "MEA")
    assert empty.eps_nm is None and empty.min_samples is None
    # a pair typed with no derivation is the user's
    typed = cp.reconcile(None, 25.0, 10)
    assert typed["eps_b_origin"] == typed["min_samples_b_origin"] == cp.ORIGIN_USER


